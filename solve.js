const byCodeUnits = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

// ---------------------------------------------------------------- text

const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const ESC_RE = /[&<>"']/g;
export function escapeHtml(text) {
  // Satu scan native (exec) + slice/concat per match — lebih cepat dari
  // test-lalu-replace (dua scan + callback per match). Regex modul-level aman:
  // escapeHtml tidak pernah memanggil balik kode pengguna (tidak re-entrant).
  let out = '';
  let start = 0;
  ESC_RE.lastIndex = 0;
  let m;
  while ((m = ESC_RE.exec(text)) !== null) {
    const i = m.index;
    if (i > start) out += text.slice(start, i);
    out += ESCAPES[text[i]];
    start = i + 1;
  }
  if (start === 0) return text;
  return out + text.slice(start);
}

const SLUG_MAX = 64;
const MARKS = /\p{M}/gu;
const slugCache = new Map();
export function slugify(text) {
  const hit = slugCache.get(text);
  if (hit !== undefined) return hit;
  const plain = text.normalize('NFKD').replace(MARKS, '');
  let out = '';
  let gap = false;
  for (let i = 0; i < plain.length; i++) {
    const c = plain.charCodeAt(i);
    let keep = 0;
    if (c >= 65 && c <= 90) keep = c + 32;
    else if ((c >= 97 && c <= 122) || (c >= 48 && c <= 57)) keep = c;
    if (keep === 0) {
      gap = out.length > 0;
      continue;
    }
    if (gap) out += '-';
    gap = false;
    out += String.fromCharCode(keep);
  }
  if (out.length > SLUG_MAX) out = out.slice(0, SLUG_MAX);
  while (out.endsWith('-')) out = out.slice(0, -1);
  if (out === '') out = 'untitled';
  slugCache.set(text, out);
  return out;
}

export function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
const dateCache = new Map();
export function longDate(date) {
  const hit = dateCache.get(date);
  if (hit !== undefined) return hit;
  const out = `${Number(date.slice(8, 10))} ${MONTHS[Number(date.slice(5, 7)) - 1]} ${date.slice(0, 4)}`;
  dateCache.set(date, out);
  return out;
}

function isSpaceCode(c) {
  if (c === 9 || c === 10 || c === 11 || c === 12 || c === 13 || c === 32) return true;
  return c === 160 || c === 5760 || (c >= 8192 && c <= 8202) || c === 8232 || c === 8233 || c === 8239 || c === 8287 || c === 12288 || c === 65279;
}

// Words: runs of non-whitespace, counted by scanning (no /\S+/g match array).
export function wordsOf(text) {
  let n = 0;
  let inWord = false;
  for (let i = 0; i < text.length; i++) {
    const c = text.charCodeAt(i);
    if (c === 9 || c === 10 || c === 11 || c === 12 || c === 13 || c === 32) inWord = false;
    else if (c < 128) { if (!inWord) { inWord = true; n++; } }
    else if (c === 160 || c === 5760 || (c >= 8192 && c <= 8202) || c === 8232 || c === 8233 || c === 8239 || c === 8287 || c === 12288 || c === 65279) inWord = false;
    else if (!inWord) { inWord = true; n++; }
  }
  return n;
}

const dirOf = (path) => (path.includes('/') ? path.slice(0, path.lastIndexOf('/')) : '');

function resolvePath(dir, rel) {
  const parts = dir === '' ? [] : dir.split('/');
  for (const seg of rel.split('/')) {
    if (seg === '' || seg === '.') continue;
    if (seg === '..') {
      if (parts.length === 0) return null;
      parts.pop();
    } else parts.push(seg);
  }
  return parts.join('/');
}

// ---------------------------------------------------------------- front matter

const KEYS = new Set(['title', 'date', 'tags', 'draft', 'layout', 'slug', 'summary']);

function daysIn(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28;
  return m === 4 || m === 6 || m === 9 || m === 11 ? 30 : 31;
}

function stringOf(raw) {
  if (raw.startsWith('"')) {
    if (raw.length < 2 || !raw.endsWith('"')) return { error: 'a quoted string is not closed' };
    const out = [];
    for (let i = 1; i < raw.length - 1; i++) {
      const c = raw[i];
      if (c === '\\') {
        const n = raw[i + 1];
        if ((n !== '"' && n !== '\\') || i + 1 === raw.length - 1) return { error: 'a quoted string holds an escape other than \\" or \\\\' };
        out.push(n);
        i++;
      } else if (c === '"') return { error: 'a quoted string holds a stray quote' };
      else out.push(c);
    }
    return { value: out.join('') };
  }
  if (raw.startsWith('[')) return { error: 'a bare string opens on [' };
  return { value: raw };
}

function isDigitCode(c) { return c >= 48 && c <= 57; }

function valueOf(key, raw) {
  switch (key) {
    case 'title':
    case 'summary': {
      const s = stringOf(raw);
      return 'error' in s ? { error: `key "${key}": ${s.error}` } : s;
    }
    case 'date': {
      let ok = raw.length === 10 && raw[4] === '-' && raw[7] === '-';
      if (ok) for (let i = 0; i < 10; i++) {
        if (i === 4 || i === 7) continue;
        if (!isDigitCode(raw.charCodeAt(i))) { ok = false; break; }
      }
      const y = ok ? Number(raw.slice(0, 4)) : 0;
      const mo = ok ? Number(raw.slice(5, 7)) : 0;
      const d = ok ? Number(raw.slice(8, 10)) : 0;
      if (!ok || y < 1970 || y > 2099 || mo < 1 || mo > 12 || d < 1 || d > daysIn(y, mo)) return { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
      return { value: raw };
    }
    case 'tags': {
      if (!raw.startsWith('[') || !raw.endsWith(']')) return { error: 'key "tags": not a list [a, b]' };
      const inner = raw.slice(1, -1);
      if (inner.trim() === '') return { value: [] };
      const tags = inner.split(',').map((t) => t.trim());
      for (const t of tags) {
        if (t === '') return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
        for (let i = 0; i < t.length; i++) {
          const ch = t[i];
          if (ch === '"' || ch === '[' || ch === ']') return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
        }
      }
      return { value: tags };
    }
    case 'draft':
      return raw === 'true' ? { value: true } : raw === 'false' ? { value: false } : { error: 'key "draft": true or false' };
    case 'layout': {
      if (raw.length === 0) return { error: 'key "layout": not a template name' };
      for (let i = 0; i < raw.length; i++) {
        const c = raw.charCodeAt(i);
        if (!((c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 45)) return { error: 'key "layout": not a template name' };
      }
      return { value: raw };
    }
    case 'slug': {
      if (raw.length === 0 || raw.length > 64 || raw[0] === '-' || raw[raw.length - 1] === '-') return { error: 'key "slug": not a slug' };
      let prevDash = false;
      for (let i = 0; i < raw.length; i++) {
        const c = raw.charCodeAt(i);
        if (c === 45) {
          if (prevDash) return { error: 'key "slug": not a slug' };
          prevDash = true;
        } else if ((c >= 97 && c <= 122) || (c >= 48 && c <= 57)) prevDash = false;
        else return { error: 'key "slug": not a slug' };
      }
      return { value: raw };
    }
    default:
      return { error: `unknown key "${key}"` };
  }
}

function isBlankLine(line) {
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (c !== ' ' && c !== '\t') return false;
  }
  return true;
}

// Parse front matter without splitting the whole body: only the header lines
// are sliced out; the body is one substring.
export function parseFrontMatter(text) {
  const firstNL = text.indexOf('\n');
  const firstLine = firstNL === -1 ? text : text.slice(0, firstNL);
  if (firstLine !== '---') return { error: 'no front matter' };
  // Find the closing line: a line exactly '---'.
  let closeStart = -1;
  let closeEnd = -1;
  // The '\n' before the closing line is at firstNL itself, so search from there.
  let searchFrom = firstNL === -1 ? 0 : firstNL;
  for (;;) {
    const cand = text.indexOf('\n---', searchFrom);
    if (cand === -1) return { error: 'the front matter is not closed' };
    const after = cand + 4;
    if (after === text.length || text[after] === '\n') { closeStart = cand + 1; closeEnd = after; break; }
    searchFrom = cand + 1;
  }
  const data = {};
  let lineStart = firstNL + 1;
  let lineNo = 2;
  while (lineStart < closeStart) {
    let lineEnd = text.indexOf('\n', lineStart);
    if (lineEnd === -1 || lineEnd >= closeStart) lineEnd = closeStart - 1;
    const line = text.slice(lineStart, lineEnd);
    if (!isBlankLine(line) && !line.startsWith('#')) {
      let k = 0;
      while (k < line.length) {
        const c = line.charCodeAt(k);
        if (!((c >= 97 && c <= 122) || c === 95)) break;
        k++;
      }
      if (k === 0 || line[k] !== ':') return { error: `line ${lineNo} is not "key: value"` };
      const key = line.slice(0, k);
      let raw;
      if (k + 1 === line.length) raw = '';
      else if (line[k + 1] === ' ') raw = line.slice(k + 2);
      else return { error: `line ${lineNo} is not "key: value"` };
      raw = raw.replace(/[ \t]+$/, '');
      if (!KEYS.has(key)) return { error: `unknown key "${key}"` };
      if (Object.hasOwn(data, key)) return { error: `key "${key}" is given twice` };
      if (raw === '') return { error: `key "${key}" has no value` };
      const v = valueOf(key, raw);
      if ('error' in v) return v;
      data[key] = v.value;
    }
    lineStart = lineEnd + 1;
    lineNo++;
  }
  if (!Object.hasOwn(data, 'title')) return { error: 'no title' };
  const body = closeEnd === text.length ? '' : text.slice(closeEnd + 1);
  return { data, body };
}

// ---------------------------------------------------------------- markdown

const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);

function isLangChar(c) {
  return (c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 95 || c === 43 || c === 45;
}

// Fence open: '```' + lang chars + spaces/tabs only. Returns lang or null.
function fenceOpen(line) {
  if (line.length < 3 || line[0] !== '`' || line[1] !== '`' || line[2] !== '`') return null;
  let j = 3;
  while (j < line.length && isLangChar(line.charCodeAt(j))) j++;
  const lang = line.slice(3, j);
  while (j < line.length && (line[j] === ' ' || line[j] === '\t')) j++;
  return j === line.length ? lang : null;
}

function fenceClose(line) {
  if (line.length < 3 || line[0] !== '`' || line[1] !== '`' || line[2] !== '`') return false;
  for (let j = 3; j < line.length; j++) if (line[j] !== ' ' && line[j] !== '\t') return false;
  return true;
}

function trimLine(line) {
  let a = 0;
  let b = line.length;
  while (a < b && (line[a] === ' ' || line[a] === '\t')) a++;
  while (b > a && (line[b - 1] === ' ' || line[b - 1] === '\t')) b--;
  return line.slice(a, b);
}

// Heading info or null (text never empty).
function headingInfo(line) {
  if (line[0] !== '#') return null;
  let n = 0;
  while (n < line.length && line[n] === '#') n++;
  if (n > 6 || n === line.length || (line[n] !== ' ' && line[n] !== '\t')) return null;
  let a = n;
  while (a < line.length && (line[a] === ' ' || line[a] === '\t')) a++;
  let b = line.length;
  while (b > a && (line[b - 1] === ' ' || line[b - 1] === '\t')) b--;
  if (b === a) return null;
  return { depth: n, text: line.slice(a, b) };
}

function isHR(line) {
  if (line.length < 3) return false;
  const c = line[0];
  if (c !== '-' && c !== '*') return false;
  if (line[1] !== c || line[2] !== c) return false;
  for (let j = 3; j < line.length; j++) if (line[j] !== ' ' && line[j] !== '\t') return false;
  return true;
}

function endsParagraph(line) {
  return isBlankLine(line) || fenceOpen(line) !== null || headingInfo(line) !== null || isHR(line);
}

// Ordered-list match: 1-9 digits, '. ', returns { start, rest } or null.
function orderedMatch(line) {
  let d = 0;
  while (d < line.length && line.charCodeAt(d) >= 48 && line.charCodeAt(d) <= 57) d++;
  if (d === 0 || d > 9) return null;
  if (line[d] !== '.' || line[d + 1] !== ' ') return null;
  return { start: Number(line.slice(0, d)), rest: line.slice(d + 2) };
}

function isContinued(line) {
  let s = 0;
  while (s < line.length && line[s] === ' ') s++;
  if (s < 2 || s >= line.length) return false;
  return !isSpaceCode(line.charCodeAt(s));
}

function findUnescaped(s, what, from) {
  // what == '**': lompat antar kandidat via indexOf; kandidat ter-escape
  // (jumlah backslash tepat sebelumnya ganjil) dilewati.
  let j = s.indexOf(what, from);
  while (j !== -1) {
    let k = j - 1;
    let n = 0;
    while (k >= 0 && s.charCodeAt(k) === 92) { n++; k--; }
    if (n % 2 === 0) return j;
    j = s.indexOf(what, j + 1);
  }
  return -1;
}

function findSingleStar(s, from) {
  let j = s.indexOf('*', from);
  while (j !== -1) {
    let k = j - 1;
    let n = 0;
    while (k >= 0 && s.charCodeAt(k) === 92) { n++; k--; }
    if (n % 2 === 1) { j = s.indexOf('*', j + 1); continue; }
    if (s.charCodeAt(j + 1) === 42) { j = s.indexOf('*', j + 2); continue; }
    return j;
  }
  return -1;
}

// Inline rendering, run-based: plain runs are escaped in bulk instead of
// one escapeHtml() call per character.
const INLINE_MARK = /[\\`*[\[]/;
export function inline(s, env) {
  // Fast path: tanpa satupun karakter spesial, inline == escapeHtml.
  if (!INLINE_MARK.test(s)) return escapeHtml(s);
  const out = [];
  const n = s.length;
  let start = 0;
  // Lompat dari satu karakter spesial ke berikutnya (regex native), bukan
  // memeriksa tiap karakter di JS. Regex dibuat per panggilan supaya rekursi
  // (strong/em/link) tidak merusak lastIndex milik pemanggil.
  const re = /[\\`*[\[]/g;
  let m;
  while ((m = re.exec(s)) !== null) {
    const i = m.index;
    const c = s.charCodeAt(i);
    if (c === 92) {
      if (i + 1 < n && ESCAPABLE.has(s[i + 1])) {
        if (i > start) out.push(escapeHtml(s.slice(start, i)));
        const nc = s.charCodeAt(i + 1);
        out.push(nc === 62 ? '&gt;' : s[i + 1]);
        start = i + 2;
        re.lastIndex = i + 2;
      } else re.lastIndex = i + 1;
      continue;
    }
    if (c === 96) {
      const j = s.indexOf('`', i + 1);
      if (j > i + 1) {
        if (i > start) out.push(escapeHtml(s.slice(start, i)));
        out.push('<code>', escapeHtml(s.slice(i + 1, j)), '</code>');
        start = j + 1;
        re.lastIndex = j + 1;
      } else re.lastIndex = i + 1;
      continue;
    }
    if (c === 42) {
      if (s.charCodeAt(i + 1) === 42) {
        const j = findUnescaped(s, '**', i + 2);
        if (j > i + 2) {
          if (i > start) out.push(escapeHtml(s.slice(start, i)));
          out.push('<strong>', inline(s.slice(i + 2, j), env), '</strong>');
          start = j + 2;
          re.lastIndex = j + 2;
        } else re.lastIndex = i + 2;
        continue;
      }
      const j = findSingleStar(s, i + 1);
      if (j > i + 1) {
        if (i > start) out.push(escapeHtml(s.slice(start, i)));
        out.push('<em>', inline(s.slice(i + 1, j), env), '</em>');
        start = j + 1;
        re.lastIndex = j + 1;
      } else re.lastIndex = i + 1;
      continue;
    }
    // c === 91 '['
    const k = findUnescaped(s, ']', i + 1);
    const mm = k !== -1 && s.charCodeAt(k + 1) === 40 ? s.indexOf(')', k + 2) : -1;
    const target = mm === -1 ? '' : s.slice(k + 2, mm);
    if (target !== '' && !/\s/.test(target)) {
      if (i > start) out.push(escapeHtml(s.slice(start, i)));
      out.push('<a href="', escapeHtml(env.link(target)), '">', inline(s.slice(i + 1, k), env), '</a>');
      start = mm + 1;
      re.lastIndex = mm + 1;
      continue;
    }
    re.lastIndex = i + 1;
  }
  if (n > start) out.push(escapeHtml(s.slice(start)));
  return out.join('');
}

// Lex + render fused: no token array, blocks are pushed straight to output.
export function renderMarkdown(src, env) {
  const lines = src.split('\n');
  const blocks = [];
  const toc = [];
  const ids = new Set();
  let excerpt = null;
  let i = 0;
  const len = lines.length;
  while (i < len) {
    const line = lines[i];
    if (isBlankLine(line)) { i++; continue; }
    const fence = fenceOpen(line);
    if (fence !== null) {
      const body = [];
      i++;
      while (i < len && !fenceClose(lines[i])) body.push(lines[i++]);
      i++;
      const cls = fence === '' ? '' : ` class="language-${escapeHtml(fence)}"`;
      const code = body.length === 0 ? '' : escapeHtml(body.join('\n') + '\n');
      blocks.push(`<pre><code${cls}>${code}</code></pre>`);
      continue;
    }
    const heading = headingInfo(line);
    if (heading !== null) {
      const id = uniqueSlug(slugify(heading.text), ids);
      const html = inline(heading.text, env);
      blocks.push(`<h${heading.depth} id="${id}">${html}</h${heading.depth}>`);
      if (heading.depth === 2 || heading.depth === 3) toc.push({ level: heading.depth, id, html });
      i++;
      continue;
    }
    if (isHR(line)) { blocks.push('<hr>'); i++; continue; }
    if (line[0] === '>') {
      const body = [];
      while (i < len && lines[i][0] === '>') {
        const l = lines[i++];
        body.push(l.length > 1 && l[1] === ' ' ? l.slice(2) : l.slice(1));
      }
      const kept = [];
      for (const l of body) {
        const t = trimLine(l);
        if (t !== '') kept.push(t);
      }
      blocks.push(kept.length === 0 ? '<blockquote>\n</blockquote>' : `<blockquote>\n<p>${inline(kept.join('\n'), env)}</p>\n</blockquote>`);
      continue;
    }
    const isBullet = (line[0] === '-' || line[0] === '*') && line[1] === ' ';
    const ord0 = isBullet ? null : orderedMatch(line);
    if (isBullet || ord0 !== null) {
      const isOrdered = ord0 !== null;
      const items = [];
      while (i < len) {
        const cur = lines[i];
        if (isOrdered) {
          const m = orderedMatch(cur);
          if (m !== null) { items.push([trimLine(m.rest)]); i++; continue; }
        } else if ((cur[0] === '-' || cur[0] === '*') && cur[1] === ' ') {
          items.push([trimLine(cur.slice(2))]); i++; continue;
        }
        if (items.length > 0 && isContinued(cur)) { items[items.length - 1].push(trimLine(cur)); i++; continue; }
        break;
      }
      const tag = isOrdered ? 'ol' : 'ul';
      const open = isOrdered && ord0.start !== 1 ? `<ol start="${ord0.start}">` : `<${tag}>`;
      let lis = '';
      for (const parts of items) lis += `<li>${inline(parts.join('\n'), env)}</li>\n`;
      blocks.push(`${open}\n${lis}</${tag}>`);
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < len && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    const html = inline(body.join('\n'), env);
    if (excerpt === null) excerpt = html;
    blocks.push(`<p>${html}</p>`);
  }
  return { html: blocks.length === 0 ? '' : blocks.join('\n') + '\n', toc, excerpt: excerpt ?? '' };
}

